/** Fallback: translate common Spanish patterns when no exact match */
export function translateString(str, pairs) {
  if (typeof str !== 'string') return str;
  if (pairs[str]) return pairs[str];
  // Keep URLs, emails, slugs, numbers, brand names unchanged
  if (/^https?:\/\//.test(str) || str.includes('@') && str.includes('.')) return str;
  if (/^[\d+~$./\s%-]+$/.test(str)) return str;
  if (/^(Next|Advance|Enterprise|Cluster|USD|TikTok|Facebook|YouTube|Instagram|Reel \d{2})$/i.test(str)) return str;
  return str;
}

export function translateTree(obj, pairs) {
  if (Array.isArray(obj)) return obj.map((item) => translateTree(item, pairs));
  if (obj && typeof obj === 'object') {
    const out = {};
    for (const [key, value] of Object.entries(obj)) {
      out[key] = translateTree(value, pairs);
    }
    return out;
  }
  if (typeof obj === 'string') return translateString(obj, pairs);
  return obj;
}

